"""Render benchmarks/SUMMARY.md from the committed result snapshots.

    uv run python benchmarks/summarize.py            # rewrite SUMMARY.md
    uv run python benchmarks/summarize.py --check    # exit 1 if SUMMARY.md is stale

The tables are a pure function of ``benchmarks/results/*.json``, so the summary can
never drift from the data it reports. Every number except those in the latency
tables reproduces exactly when the benchmarks are re-run. Latency is
machine-dependent and labeled as such.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
RESULTS = HERE / "results"
SUMMARY = HERE / "SUMMARY.md"
APP_LABELS = {"fintech": "Fintech (wallets, loans)", "saas": "B2B SaaS (workspaces, billing)",
              "agent_gateway": "AI agent / MCP gateway"}


def _load(name: str) -> dict:
    return json.loads((RESULTS / f"{name}.json").read_text())


def _pct(x: float | None, digits: int = 1) -> str:
    return "n/a" if x is None else f"{x * 100:.{digits}f}%"


def _table(header: list[str], rows: list[list[object]], align: str | None = None) -> str:
    align = align or "l" + "r" * (len(header) - 1)
    marks = [":---" if a == "l" else "---:" for a in align]
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(marks) + " |"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def render() -> str:
    compile_ = _load("compile_fintech")
    ablation = _load("search_ablation")
    remed = _load("remediation_bench")
    rlvr = _load("rlvr_stats")
    apps = remed["apps"]
    out: list[str] = [
        "# Cubic benchmark summary",
        "",
        "Generated by `benchmarks/summarize.py` from `benchmarks/results/*.json`. Do not edit by hand.",
        f"Cubic {remed['cubic_version']}; every verification replays a trace "
        f"{remed['runs_per_candidate']}x on a freshly seeded app and counts it only if it reproduces every time.",
        "",
        "Each Bug Gym app has 4 independently togglable planted defects and 6 builds (patched, one per bug, "
        "all bugs), so there are 8 (build, bug) pairs to find per app. Recall@1 counts a bug as found only if "
        "the *first* planned test for its invariant is confirmed. FPR is computed over every planned test whose "
        "invariant no active bug breaks.",
        "",
        "## 1. Detection: compile -> search -> verify, no hand-written probes",
        "",
        _table(
            ["App", "Edges", "Invariants", "Plan tests", "Coverage", "Recall@1", "FPR", "Recall@1 (ungrounded)",
             "FPR (ungrounded)"],
            [[APP_LABELS.get(k, k), a["graph"]["edges"], a["graph"]["invariants"], a["plan_tests"],
              f"{a['invariants_covered']}/{a['graph']['invariants']}",
              f"{_pct(a['detection']['grounded']['recall_at_1'])} "
              f"({a['detection']['grounded']['bugs_found_at_1']}/{a['detection']['grounded']['bugs_total']})",
              f"{_pct(a['detection']['grounded']['false_positive_rate'])} "
              f"(0 of {a['detection']['grounded']['negatives']})"
              if a['detection']['grounded']['false_positives'] == 0 else
              f"{_pct(a['detection']['grounded']['false_positive_rate'])}",
              _pct(a["detection"]["ungrounded_m3_policy"]["recall_at_1"]),
              _pct(a["detection"]["ungrounded_m3_policy"]["false_positive_rate"])]
             for k, a in apps.items()],
        ),
        "",
        "*Ungrounded* is the Milestone 3 policy: persona ties break on id, and seeded resources are assumed to "
        "be in their initial state. *Grounded* ranks personas by state observed at compile time "
        "(balances, lifecycle status, preconditions).",
        "",
        "## 2. Search ablation (fintech)",
        "",
        "### 2a. False-positive filtering",
        "",
    ]
    fp = ablation["fp_filtering"]
    rows = []
    for label, key in (("Guided plan", "guided_plan"), ("Full combinator pool, no policy", "full_pool_no_policy")):
        for mode in ("unfiltered", "verifier_gated"):
            m = fp[key][mode]
            rows.append([f"{label}, {'unfiltered' if mode == 'unfiltered' else 'verifier-gated'}",
                         fp[key]["proposals"], m["reported_findings"], m["true_positives"], m["false_positives"],
                         _pct(m["precision"]), _pct(m["false_positive_rate"])])
    out += [
        _table(["Configuration", "Tests", "Reported", "TP", "FP", "Precision", "FPR"], rows),
        "",
        "The 3-of-3 verifier removes results that don't reproduce. Tests whose oracle is ambiguous "
        "(e.g. an admin \"intruder\" who is allowed to read any wallet) reproduce deterministically, "
        "and only the guard-aware policy removes them.",
        "",
        "### 2b. Graph-guided search vs. uniform random edge sampling",
        "",
    ]
    g, r = ablation["search_efficiency"]["graph_guided"], ablation["search_efficiency"]["uniform_random_edge"]
    out += [
        _table(
            ["Strategy", "Budget", "Recall@1", "Runs with full Recall@1", "Runs with any FP",
             "Tests to full recall (all-bugs build)"],
            [["Graph-guided (heuristic policy)", g["budget"], _pct(g["recall_at_1"]), "deterministic",
              "0" if g["false_positives_gated"] == 0 else g["false_positives_gated"],
              g["tests_to_full_recall"]["vulnerable"]],
             [f"Uniform random edge sampling ({r['seeds']} seeds)", r["budget"],
              f"{_pct(r['recall_at_1']['mean'])} mean", f"{r['runs_with_full_recall_at_1']}/{r['seeds']}",
              f"{r['runs_with_any_false_positive']}/{r['seeds']}",
              f"{r['tests_to_full_recall_vulnerable']['mean']:.1f} mean "
              f"(min {r['tests_to_full_recall_vulnerable']['min']}, max {r['tests_to_full_recall_vulnerable']['max']})"]],
            align="lrrrrr",
        ),
        "",
        "## 3. Closed-loop remediation",
        "",
        _table(
            ["App", "Confirmed findings", "Verified patches", "First-attempt pass", "Regression tests valid",
             "Rules used"],
            [[APP_LABELS.get(k, k), a["remediation"]["totals"]["findings"],
              f"{a['remediation']['totals']['verified_patches']} ({_pct(a['remediation']['totals']['patch_pass_rate'], 0)})",
              sum(v["first_attempt_pass"] for v in a["remediation"]["by_variant"].values()),
              a["remediation"]["totals"]["regression_tests_valid"],
              ", ".join(f"{rule.removeprefix('rule:')} x{n}" for rule, n in a["remediation"]["rules"].items())]
             for k, a in apps.items()],
            align="lrrrrl",
        ),
        "",
        f"Across all apps: **{remed['summary']['verified_patches']}/{remed['summary']['findings_remediated']}** "
        "findings get a patch that passes the gate. The gate requires the exploit to reproduce on 0 of 3 runs and "
        "every previously passing functional QA test to still pass. A regression test is *valid* when the "
        "exported standalone pytest file fails on the unpatched build and passes on the patched code.",
        "",
        "## 4. RLVR trajectory dataset",
        "",
    ]
    splits = rlvr["splits"]
    out += [
        _table(
            ["Split", "Apps", "Rows", "Prompts", "Reward +1", "Reward 0", "Reward -1", "Mean reward",
             "Search-plan mean", "Policy-pruned mean"],
            [[s, ", ".join(v["envs"]), v["rows"], v["prompts"], v["reward_histogram"].get("+1.0", 0),
              v["reward_histogram"].get("+0.0", 0), v["reward_histogram"].get("-1.0", 0),
              f"{v['mean_reward']:+.3f}", f"{v['search_plan_mean_reward']:+.3f}",
              f"{v['policy_pruned_mean_reward']:+.3f}"]
             for s, v in sorted(splits.items(), key=lambda kv: kv[0] != "train")],
            align="llrrrrrrrr",
        ),
        "",
        f"{rlvr['rows']} trajectories (sha256 `{rlvr['sha256'][:16]}`), "
        f"{rlvr['runs_per_verification']} replays per verification. "
        f"Shared prompts across splits: {rlvr['leakage']['shared_prompts']}. Rewards: "
        + ", ".join(f"`{k}` {v:+.1f}" for k, v in rlvr["reward_scheme"].items())
        + ". The gap between search-plan and policy-pruned rows means the heuristic policy's choices already "
        "line up with the verifiable reward, which makes it a reasonable initial policy for RL fine-tuning.",
        "",
        "## 5. Compiler (fintech)",
        "",
        _table(
            ["Routes", "Structural fidelity", "Nodes", "Edges", "Invariants", "Source bytes", "Graph bytes",
             "Structural graph bytes", "Source / structural graph"],
            [[f"{compile_['routes']['compiled']}/{compile_['routes']['total']}",
              f"{compile_['fidelity']['structural_fidelity']:.2f}", compile_["graph"]["nodes"],
              compile_["graph"]["edges"], compile_["graph"]["invariants"], compile_["bytes"]["source"],
              compile_["bytes"]["compiled_graph"], compile_["bytes"]["structural_graph"],
              f"{compile_['compression']['source_over_structural_graph']:.2f}x"]],
        ),
        "",
        "## 6. Latency (machine-dependent)",
        "",
        f"Measured on {remed['latency_s']['platform']}, Python {remed['latency_s']['python']}.",
        "",
        _table(
            ["App", "Compile", "Search", "Verify plan", "Patch + gate", "Export + check", "Total `cubic remediate`"],
            [[APP_LABELS.get(k, k), *(f"{t[stage]:.2f} s" for stage in
                                      ("compile", "search", "verify", "patch_and_verify", "export", "total"))]
             for k, t in remed["latency_s"]["remediate_vulnerable"].items()],
        ),
        "",
        f"Compiler alone (fintech, median of {compile_['iterations']}): "
        f"{compile_['latency']['total']['median_ms']:.1f} ms total, "
        f"{compile_['latency']['grounding']['median_ms']:.1f} ms of it persona grounding.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "uv run python benchmarks/compile_bench.py --iterations 25",
        "uv run python benchmarks/ablation_search.py --runs 3 --seeds 200",
        "uv run python benchmarks/remediation_bench.py --runs 3",
        "uv run cubic export-rlvr --out datasets/cubic_rlvr.jsonl \\",
        "    --sample-out datasets/cubic_rlvr_sample.jsonl --stats benchmarks/results/rlvr_stats.json",
        "uv run python benchmarks/summarize.py",
        "```",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Fail if SUMMARY.md is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not SUMMARY.exists() or SUMMARY.read_text() != text:
            print("benchmarks/SUMMARY.md is stale; run benchmarks/summarize.py", file=sys.stderr)
            return 1
        return 0
    SUMMARY.write_text(text)
    print(f"wrote {SUMMARY}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
