"""Compile a confirmed finding into a permanent, standalone ``pytest`` regression test.

The generated file depends only on ``pytest``, ``httpx`` and the application
module. It does not import QbQ. It replays the exact exploit trace in-process
over ASGI, using barrier-synchronized concurrency where the trace needs it, and
checks the violated invariant with inline assertions: status codes, ledger
conservation over the app's snapshot hook, and state guards. It runs three times,
like the verifier. It passes on a fixed build and fails if the defect returns.

Persona credentials in the trace are the seeded test tokens from the graph. The
exported test needs them to authenticate against the in-process app.
"""

from __future__ import annotations

import pprint
import re
from pathlib import Path

from qbq.graph import LedgerConservationCheck, StateGraph, StateGuardCheck, StatusCodeCheck
from qbq.gym.base import AppSource
from qbq.remediate.models import ConfirmedFinding


def regression_file_name(invariant_id: str) -> str:
    return f"test_regression_{re.sub(r'[^A-Za-z0-9]+', '_', invariant_id).strip('_').lower()}.py"


def _steps(graph: StateGraph, finding: ConfirmedFinding) -> list[dict]:
    out = []
    for step in finding.candidate.trace.steps:
        edge, actor = graph.edge(step.edge_id), graph.actor(step.actor_id)
        out.append({
            "edge": edge.id, "actor": actor.id, "method": edge.method.value,
            "path": edge.render_path(step.path_params), "headers": actor.auth_headers(),
            "json": step.body, "concurrency": step.concurrency,
        })
    return out


def _checks(finding: ConfirmedFinding) -> list[dict]:
    out = []
    for check in finding.invariant.checks:
        if isinstance(check, StatusCodeCheck):
            out.append({"kind": "status_code", "step": check.step, "allowed": sorted(check.allowed)})
        elif isinstance(check, LedgerConservationCheck):
            out.append({"kind": "ledger_conservation", "entity": check.entity,
                        "balance_field": check.balance_field, "account_field": check.account_field,
                        "account_ids": sorted(check.account_ids) if check.account_ids else None,
                        "allow_negative": check.allow_negative})
        elif isinstance(check, StateGuardCheck):
            out.append(check.model_dump(mode="json"))
    return out


_TEMPLATE = '''\
"""Regression test generated by QbQ from a verified finding.

Invariant : {invariant_id} ({category}, {severity})
            {description}
Finding   : {finding_id}
Hypothesis: {hypothesis}

The trace below broke the invariant 3 of 3 times in QbQ's deterministic sandbox.
This test replays it in-process and asserts the invariant holds. Keep it in CI so
the defect cannot silently return.
"""

import asyncio

import httpx
import pytest

from {module} import {factory} as _create_app
{snapshot_import}
APP_FACTORY_ARGS = ()

STEPS = {steps}

CHECKS = {checks}


def make_app():
    return _create_app(*APP_FACTORY_ARGS)


async def _replay(app):
    transport = httpx.ASGITransport(app=app)
    async with httpx.AsyncClient(transport=transport, base_url="http://regression") as client:
        statuses = []
        for step in STEPS:
            async def send(step=step):
                response = await client.request(
                    step["method"], step["path"], headers=step["headers"], json=step["json"]
                )
                return response.status_code

            if step["concurrency"] == 1:
                statuses.append([await send()])
                continue
            barrier = asyncio.Barrier(step["concurrency"])

            async def fire(send=send, barrier=barrier):
                await barrier.wait()
                return await send()

            statuses.append(list(await asyncio.gather(*(fire() for _ in range(step["concurrency"])))))
        return statuses


def _assert_invariant(statuses, state):
    for check in CHECKS:
        if check["kind"] == "status_code":
            got = statuses[check["step"]]
            bad = sorted({{s for s in got if s not in check["allowed"]}})
            assert not bad, f"step {{check['step']}} returned {{bad}}, allowed {{check['allowed']}}"
        elif state is None:
            continue  # the app exposes no state hook: only status checks apply
        elif check["kind"] == "ledger_conservation":
            accounts = state.entities.get(check["entity"], {{}})
            for account_id in check["account_ids"] or sorted(accounts):
                balance = accounts[account_id][check["balance_field"]]
                ledger = sum(e["amount"] for e in state.ledger if e.get(check["account_field"]) == account_id)
                assert balance == ledger, f"{{account_id}}: balance {{balance}} != ledger sum {{ledger}}"
                assert check["allow_negative"] or balance >= 0, f"{{account_id}}: negative balance {{balance}}"
        elif check["kind"] == "state_guard":
            row = state.entities.get(check["entity"], {{}}).get(check["entity_id"])
            if row is not None and row.get(check["when_field"]) == check["when_value"]:
                required = state.entities.get(check["require_entity"], {{}}).get(check["require_id"]) or {{}}
                assert required.get(check["require_field"]) == check["require_value"], "state guard violated"


@pytest.mark.parametrize("run", range(3))
def {test_name}(run):
    app = make_app()
    statuses = asyncio.run(_replay(app))
    state = {state_expr}
    _assert_invariant(statuses, state)
'''


def render_regression_test(finding: ConfirmedFinding, graph: StateGraph, app_source: AppSource) -> str:
    checks = _checks(finding)
    needs_state = any(c["kind"] != "status_code" for c in checks) and app_source.snapshot is not None
    name = regression_file_name(finding.invariant.id).removesuffix(".py")
    return _TEMPLATE.format(
        invariant_id=finding.invariant.id, category=finding.invariant.category.value,
        severity=finding.invariant.severity.value, description=finding.invariant.description,
        finding_id=finding.id, hypothesis=finding.candidate.hypothesis,
        module=app_source.module, factory=app_source.factory,
        snapshot_import=(f"from {app_source.module} import {app_source.snapshot} as _snapshot\n"
                         if needs_state else ""),
        steps=pprint.pformat(_steps(graph, finding), sort_dicts=True, width=100),
        checks=pprint.pformat(checks, sort_dicts=True, width=100),
        test_name=name, state_expr="_snapshot(app)" if needs_state else "None",
    )


def export_regression_test(
    finding: ConfirmedFinding, graph: StateGraph, app_source: AppSource, out_dir: Path | str
) -> Path:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    path = out / regression_file_name(finding.invariant.id)
    path.write_text(render_regression_test(finding, graph, app_source), encoding="utf-8")
    return path
